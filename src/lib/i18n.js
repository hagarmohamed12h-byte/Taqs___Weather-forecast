export function detectLang() {
    if (typeof navigator === "undefined") return "en";
    return (navigator.language || "en").toLowerCase().startsWith("ar") ? "ar" : "en";
}

export function makeFormat(lang) {
    const { locale } = LANGS[lang];
    const num = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
    const num1 = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
    const num3 = new Intl.NumberFormat(locale, { minimumFractionDigits: 3, maximumFractionDigits: 3 });

    // Open-Meteo returns local wall-clock strings (no offset) when timezone=auto,
    // so they are read as UTC and formatted as UTC to keep the city's own clock.
    const asDate = (iso) => new Date(iso.length === 10 ? iso : `${iso}Z`);

    const longDate = new Intl.DateTimeFormat(locale, { weekday: "long", day: "numeric", month: "long", timeZone: "UTC" });
    const weekdayLong = new Intl.DateTimeFormat(locale, { weekday: "long", timeZone: "UTC" });
    const weekdayShort = new Intl.DateTimeFormat(locale, { weekday: lang === "ar" ? "long" : "short", timeZone: "UTC" });
    const hour = new Intl.DateTimeFormat(locale, { hour: "numeric", timeZone: "UTC" });
    const time = new Intl.DateTimeFormat(locale, { hour: "numeric", minute: "2-digit", timeZone: "UTC" });

    return {
        num: (n) => num.format(Math.round(n) + 0),
        num1: (n) => num1.format(n),
        coord: (n) => num3.format(Math.abs(n)),
        temp: (n) => `${num.format(Math.round(n) + 0)}°`,
        longDate: (iso) => longDate.format(asDate(iso)),
        weekdayLong: (iso) => weekdayLong.format(asDate(iso)),
        weekdayShort: (iso) => weekdayShort.format(asDate(iso)),
        hour: (iso) => hour.format(asDate(iso)),
        time: (iso) => time.format(asDate(iso)),
    };
}
